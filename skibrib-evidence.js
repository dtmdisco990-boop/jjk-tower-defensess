/* SKIBRIB evidence run: plays complete Wave-1-to-75 attempts with the optimizing bot and with weaker strategies, in parallel worker
   processes, and writes docs/SKIBRIB-EVIDENCE.md. Every run is legitimate: real starting Yen, no god mode, no debug tools.
   Usage: node tests/dev/skibrib-evidence.js [seeds=16] [ablationSeeds=4]   (about 10 minutes on 2 cores) */
'use strict';
const path = require('path');
const fs = require('fs');
const os = require('os');
const { execFile } = require('child_process');

if (process.argv[2] === '--one') {
  // worker: one run, prints one JSON line
  const job = JSON.parse(process.argv[3]);
  const { loadGame } = require('../load.js');
  const J = loadGame();
  const team = job.team;
  const b = new J.Battle({ mapId: 'skibrib', diff: 'skibrib', team: team.map((id) => ({ id, level: job.level, stars: job.stars })), seed: job.seed });
  const lostBy = {}; const bossProg = {}; let peak = 0, minLives = 15;
  b.events.on('leak', (e) => { if (!e.enemy.boss) lostBy[b.wave] = (lostBy[b.wave] || 0) + e.enemy.leak; else lostBy[b.wave] = 'BOSS ESCAPED'; });
  b.events.on('bossDeath', (e) => { bossProg[e.enemy.type] = Math.round(e.enemy.dist / e.enemy.pathLen * 100); });
  const t0 = Date.now();
  let s;
  if (job.profile === 'genericBot') {
    const step = J.Balance.STEP; let dT = 0;
    const order = b.teamOrder.slice().sort((x, y) => b.roster[x].cost - b.roster[y].cost);
    while (!b.over && b.time < 14000) { dT -= step; if (dT <= 0) { dT = 0.4; J.Bot.decide(b, order, 'good', true, {}); } b.update(step); if (b.enemies.length > peak) peak = b.enemies.length; }
    s = b.getSummary();
  } else {
    const SB = require('../skibrib-bot.js').makeBot(J);
    const bot = new SB(b, { profile: job.profile });
    while (!b.over && b.time < 14000) { bot.step(); if (b.enemies.length > peak) peak = b.enemies.length; }
    s = b.getSummary();
  }
  console.log(JSON.stringify({ job, victory: s.victory, wave: s.wave, lives: s.baseHp, simSeconds: s.duration, ms: Date.now() - t0, lostBy, bossProg, peak, deploys: s.deploys, sold: s.sold, domains: s.domains, debug: s.debug }));
  process.exit(0);
}

const args = Object.fromEntries(process.argv.slice(2).map((x) => x.split('=')));
const SEEDS = +(args.seeds || 16), ASEEDS = +(args.ablationSeeds || 4);
const PROOF = ['yuji', 'megumi', 'choso', 'mahitoC', 'gojo', 'jogoC'];
const jobs = [];
for (let s = 1; s <= SEEDS; s++) jobs.push({ group: 'optimal', profile: 'optimal', team: PROOF, level: 30, stars: 5, seed: s });
for (const prof of ['noTargeting', 'spamDomains', 'noDomains', 'greedy', 'sloppyPlacement', 'casual']) for (let s = 1; s <= ASEEDS; s++) jobs.push({ group: prof, profile: prof, team: PROOF, level: 30, stars: 5, seed: s });
for (let s = 1; s <= ASEEDS; s++) jobs.push({ group: 'genericBot', profile: 'genericBot', team: PROOF, level: 30, stars: 5, seed: s });
for (let s = 1; s <= ASEEDS; s++) jobs.push({ group: 'optimal Lv20 0★', profile: 'optimal', team: PROOF, level: 20, stars: 0, seed: s });
for (let s = 1; s <= ASEEDS; s++) jobs.push({ group: 'optimal, alt team (Hakari/Yuki instead of Gojo/Jogo)', profile: 'optimal', team: ['yuji', 'megumi', 'choso', 'mahitoC', 'hakari', 'yuki'], level: 30, stars: 5, seed: s });
for (let s = 1; s <= ASEEDS; s++) jobs.push({ group: 'optimal, whale team (no Yuji/Megumi)', profile: 'optimal', team: ['sukunaC', 'gojo', 'mahitoC', 'yuta', 'higuruma', 'choso'], level: 30, stars: 5, seed: s });

const N = Math.max(1, os.cpus().length);
const results = []; let i = 0, active = 0;
const t0 = Date.now();
function next() {
  if (i >= jobs.length) { if (!active) done(); return; }
  const j = jobs[i++]; active++;
  execFile('node', [__filename, '--one', JSON.stringify(j)], { maxBuffer: 1e7 }, (err, out) => {
    active--;
    try { results.push(JSON.parse(String(out).trim().split('\n').pop())); } catch (e) { results.push({ job: j, error: String(err || out) }); }
    process.stdout.write('\r' + results.length + '/' + jobs.length + ' runs');
    next();
  });
}
for (let k = 0; k < N; k++) next();

function done() {
  const groups = {};
  for (const r of results) (groups[r.job.group] = groups[r.job.group] || []).push(r);
  const lines = [];
  lines.push('# SKIBRIB CHALLENGE: simulation evidence', '');
  lines.push('Generated by `node tests/dev/skibrib-evidence.js` on ' + new Date().toISOString().slice(0, 10) + ' (' + results.length + ' complete Wave-1-to-75 attempts, ' + Math.round((Date.now() - t0) / 1000) + 's on ' + N + ' cores).', '');
  lines.push('Every run is legitimate: normal starting Yen, normal lives, no god mode, no debug tools, no stat edits. Characters are at Lv 30 / 5★ unless noted (obtainable by playing). The optimal strategy is `tests/skibrib-bot.js` (profile `optimal`); the weaker strategies are the same bot with one skill switched off, plus the game\'s generic autoplay bot.', '');
  lines.push('Proof team: ' + PROOF.join(', ') + '.', '');
  lines.push('| Strategy | Runs | Clears | Wave of death (each run) | Lives left on clears |', '|---|---|---|---|---|');
  for (const g of Object.keys(groups)) {
    const rs = groups[g].sort((a, b) => a.job.seed - b.job.seed);
    const wins = rs.filter((r) => r.victory);
    lines.push('| ' + g + ' | ' + rs.length + ' | ' + wins.length + ' | ' + rs.map((r) => (r.victory ? 'WIN' : r.wave)).join(', ') + ' | ' + (wins.map((r) => r.lives).join(', ') || '-') + ' |');
  }
  lines.push('', '## Optimal runs in detail', '', '| Seed | Result | Lives | Lives lost by wave | Boss progress at death (% of path) | Peak enemies alive | Sim time |', '|---|---|---|---|---|---|---|');
  for (const r of (groups.optimal || []).sort((a, b) => a.job.seed - b.job.seed)) {
    lines.push('| ' + r.job.seed + ' | ' + (r.victory ? '**CLEAR**' : 'died on ' + r.wave) + ' | ' + r.lives + ' | ' + Object.entries(r.lostBy).map(([w, n]) => w + ':' + n).join(' ') + ' | ' + Object.entries(r.bossProg).map(([k, v]) => k.replace('skib', '') + ' ' + v + '%').join(', ') + ' | ' + r.peak + ' | ' + Math.round(r.simSeconds / 60) + ' min |');
  }
  const out = path.join(__dirname, '..', '..', 'docs', 'SKIBRIB-EVIDENCE.md');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, lines.join('\n') + '\n');
  console.log('\n' + lines.join('\n'));
}
